"use client";

import { useEffect, useRef } from "react";
import { useReducedMotion } from "@/lib/collected/useReducedMotion";
import styles from "./SafetyCards.module.css";

type Copy = { title: string; description: string };
type Cards = readonly [Copy, Copy, Copy];
type Props = {
  theme?: "light" | "dark";
  heading?: string;
  cards?: Cards;
  learnMoreHref?: string;
  animated?: boolean;
};

const defaultCards: Cards = [
  { title: "Moderation", description: "We monitor the content people create with our tools." },
  { title: "Accountability", description: "Misusing our tools has consequences." },
  { title: "Provenance", description: "You should know when audio was generated by AI." },
];

type Pen = CanvasRenderingContext2D;
type Point = readonly [x: number, y: number];
const size = 202;
const turn = Math.PI * 2;
const cycleMs = [6400, 7800, 7100];
const visibleFraction = 0.15;

function lines(pen: Pen, ...segments: Point[][]) {
  pen.beginPath();
  for (const [start, ...points] of segments) {
    pen.moveTo(...start);
    for (const point of points) pen.lineTo(...point);
  }
  pen.stroke();
}

function guides(pen: Pen, draw: () => void) {
  pen.save();
  pen.lineWidth = 1.05;
  pen.setLineDash([0.2, 3.9]);
  draw();
  pen.restore();
}

function ellipse(pen: Pen, x: number, y: number, rx: number, ry = rx) {
  pen.beginPath();
  pen.ellipse(x, y, rx, ry, 0, 0, Math.PI * 2);
  pen.stroke();
}

function cone(pen: Pen, origin: Point, x: number, y: number, rx: number, ry: number) {
  // The cone edges meet the ellipse at its tangent points.
  const u = (origin[0] - x) / rx;
  const v = (origin[1] - y) / ry;
  const distance = u * u + v * v;
  const tangent = Math.sqrt(distance - 1);
  const tangentPoint = (side: number): Point => [
    x + rx * (u + side * v * tangent) / distance,
    y + ry * (v - side * u * tangent) / distance,
  ];
  lines(pen, [tangentPoint(1), origin, tangentPoint(-1)]);
  ellipse(pen, x, y, rx, ry);
}

function moderation(pen: Pen, phase: number, strength: number) {
  const origin: Point = [90, 154];
  const wave = Math.sin(phase) * strength;
  const opening = (1 - Math.cos(phase)) * strength / 2;
  guides(pen, () => lines(pen, [[1, 154], [201, 154]], [[90, 17], origin, [46, 198]]));
  cone(pen, origin, 46 - 4 * wave, 120 + 6 * wave, 15 + 7 * opening, 57 + 10 * wave);
  cone(pen, origin, 161 + 3 * wave, 98 + 3 * wave, 24 + 6 * opening, 93 - 13 * opening);
}

function accountability(pen: Pen, phase: number, strength: number) {
  const depth = (1 - Math.cos(phase)) * strength / 2;
  const tilt = Math.sin(phase) * strength;
  const front = (x: number, y: number): Point => [6 + 144 * x, 43 + 144 * y];
  const back = (x: number, y: number): Point => [
    51 + 144 * x - 17 * depth,
    14 + 144 * y + (5 + 6 * x) * tilt,
  ];
  guides(pen, () => lines(pen,
    [front(0, 1), back(1, 0)], [front(0, 0), back(1, 1)], [back(0, 0), front(1, 1)],
  ));
  for (const plane of [front, back]) {
    lines(pen, [plane(0, 0), plane(1, 0), plane(1, 1), plane(0, 1), plane(0, 0)],
      [plane(0.5, 0), plane(0.5, 1)], [plane(0, 0.5), plane(1, 0.5)]);
  }
  for (const x of [0, 0.5, 1]) {
    lines(pen, [front(x, 0), back(x, 0)], [front(x, 1), back(x, 1)]);
  }
  lines(pen, [front(0, 0.5), back(0, 0.5)], [front(1, 0.5), back(1, 0.5)]);
}

function provenance(pen: Pen, phase: number, strength: number) {
  const angle = Math.PI + 0.2 * strength * Math.sin(phase);
  guides(pen, () => ellipse(pen, 101, 101, 99.7));
  for (let ring = 0; ring < 6; ring++) {
    const radius = 55 + ring * 7.5 + 4 * strength * Math.sin(phase - ring * 0.38);
    const offset = 99.7 - radius;
    ellipse(pen, 101 + offset * Math.cos(angle), 101 + offset * Math.sin(angle), radius);
  }
}

const drawDiagrams = [moderation, accountability, provenance];

function SafetyCard({ card, index, theme, animated }: { card: Copy; index: number; theme: Props["theme"]; animated: boolean }) {
  const canvas = useRef<HTMLCanvasElement>(null);
  const motion = useRef({ hovered: false, sync: null as (() => void) | null });

  useEffect(() => {
    const element = canvas.current;
    const pen = element?.getContext("2d");
    if (!element || !pen) return;

    const ratio = window.devicePixelRatio || 1;
    element.width = Math.ceil(size * ratio);
    element.height = Math.ceil(size * ratio);
    pen.setTransform(element.width / size, 0, 0, element.height / size, 0, 0);
    pen.strokeStyle = getComputedStyle(element).color;
    pen.lineWidth = 0.75;
    pen.lineCap = "round";
    const draw = (phase: number, strength: number) => {
      pen.clearRect(0, 0, size, size);
      drawDiagrams[index](pen, phase, strength);
    };
    draw(0, 0);
    if (!animated) return;

    const playback = motion.current;
    const cardElement = element.closest("li");
    const startPhase = index * 0.65;
    let inView = false;
    let phase = startPhase;
    let strength = 0;
    let frame: number | undefined;
    let previousTime: number | undefined;

    function stop() {
      if (frame !== undefined) cancelAnimationFrame(frame);
      frame = undefined;
      previousTime = undefined;
    }

    function tick(now: number) {
      // Use elapsed time at any refresh rate, with a cap for delayed frames.
      const elapsed = Math.min(now - (previousTime ?? now), 40);
      previousTime = now;
      strength += (1.16 - strength) * (1 - Math.exp(-elapsed / 290));
      phase = (phase + turn * elapsed / cycleMs[index]) % turn;
      draw(phase, strength);
      frame = requestAnimationFrame(tick);
    }

    const sync = () => {
      if (!playback.hovered || !cardElement?.matches(":hover") || !inView || document.hidden || getComputedStyle(element).visibility !== "visible") {
        if (frame === undefined) return;
        stop();
        phase = startPhase;
        strength = 0;
        draw(0, 0);
      } else if (frame === undefined) {
        frame = requestAnimationFrame(tick);
      }
    };

    const observer = new IntersectionObserver(([entry]) => {
      inView = entry.intersectionRatio >= visibleFraction;
      sync();
    }, { threshold: visibleFraction });
    observer.observe(element);
    document.addEventListener("visibilitychange", sync);
    // Collected keeps inactive previews mounted so their layout stays stable.
    const pane = element.closest('[role="tabpanel"]');
    const paneObserver = pane ? new MutationObserver(sync) : null;
    if (pane && paneObserver) paneObserver.observe(pane, { attributes: true, attributeFilter: ["class", "hidden"] });
    playback.sync = sync;

    return () => {
      playback.sync = null;
      observer.disconnect();
      paneObserver?.disconnect();
      document.removeEventListener("visibilitychange", sync);
      stop();
    };
  }, [index, theme, animated]);

  return (
    <li className={styles.card} onPointerEnter={(event) => {
      if (event.pointerType !== "mouse") return;
      motion.current.hovered = true;
      motion.current.sync?.();
    }} onPointerLeave={() => {
      motion.current.hovered = false;
      motion.current.sync?.();
    }}>
      <div className={styles.art} aria-hidden="true">
        <canvas ref={canvas} width={size} height={size} />
      </div>
      <div className={styles.caption}>
        <h3>{card.title}</h3>
        <p>{card.description}</p>
      </div>
    </li>
  );
}

export default function SafetyCards({
  theme = "light",
  heading = "Safety, built in",
  cards = defaultCards,
  learnMoreHref = "https://elevenlabs.io/safety",
  animated = true,
}: Props) {
  const reduced = useReducedMotion();
  return (
    <section className={styles.root} data-collected="safety-cards" data-theme={theme} aria-label={heading}>
      <div className={styles.layout}>
        <header className={styles.header}>
          <h2>{heading}</h2>
          <a className={styles.link} href={learnMoreHref}>Learn more</a>
        </header>
        <ul className={styles.cards}>
          {cards.map((card, index) => <SafetyCard key={index} card={card} index={index} theme={theme} animated={animated && !reduced} />)}
        </ul>
      </div>
    </section>
  );
}
